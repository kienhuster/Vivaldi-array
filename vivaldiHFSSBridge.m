function out = vivaldiHFSSBridge(action, varargin)
    % VIVALDIHFSSBRIDGE Generate auditable VBScript and run AEDT asynchronously.
    % generate(mode,cfg,params) is portable. launch(job,exe) requires Windows.
    addpath(fullfile(fileparts(mfilename('fullpath')), 'SingleElementBuilder'));
    switch lower(action)
        case 'detect'
            out = HFSSRuntimeSupport.findExecutables(varargin{:});
        case 'generate'
            out = generate(varargin{:});
        case 'launch'
            job = varargin{1};
            exe = varargin{2};
            assert(ispc, 'Vivaldi:HFSSUnavailable', 'HFSS Automation/VBScript này cần Windows. GUI offline vẫn dùng được.');
            try
                exe = HFSSRuntimeSupport.resolveExecutable(exe);
            catch err
                error('Vivaldi:HFSSUnavailable', '%s', err.message);
            end
            assert(usejava('jvm'), 'Vivaldi:HFSSUnavailable', 'MATLAB JVM is required to launch HFSS.');
            % ProcessBuilder passes separate arguments: no shell injection or blocking wait.
            args = java.util.ArrayList();
            args.add(exe);
            args.add('-RunScript');
            args.add(job.script);
            builder = java.lang.ProcessBuilder(args);
            builder.redirectErrorStream(true);
            builder.redirectOutput(java.io.File(job.console));
            job.process = builder.start();
            out = job;
        case 'poll'
            job = varargin{1};
            out = struct('state', 'LAUNCHED', 'log', '', 'alive', true, 'terminal', false);
            if isfile(job.status)
                raw = HFSSRuntimeSupport.readUTF16(job.status);
                out.log = raw;
                ending = find(raw == char(10), 1, 'last');
                if isempty(ending)
                    raw = '';
                else
                    raw = raw(1:ending);
                end
                lines = regexp(raw, '\r?\n', 'split');
                for k = 1:numel(lines)
                    token = regexp(lines{k}, '^STATE\|([A-Z_]+)\|', 'tokens', 'once');
                    if ~isempty(token)
                        out.state = token{1};
                    end
                end
            end
            out.terminal = ismember(out.state, {'FAILED', 'CONNECTED', 'UPDATED', 'VALIDATED', ...
                                                'VALIDATION_UNVERIFIED', 'SIMULATED', 'SOLVE_RETURNED_UNVERIFIED'});
            if strcmp(out.state, 'CONNECTED') && ~strcmp(job.mode, 'connect')
                out.terminal = false;
            end
            if isfield(job, 'process') && ~isempty(job.process)
                out.alive = job.process.isAlive();
                if ~out.alive && ~out.terminal
                    out.state = 'WAITING_FOR_SCRIPT';
                    out.log = [out.log newline 'Launcher exited; HFSS may have dispatched the script to an existing Desktop. Awaiting its terminal status.'];
                end
            end
        otherwise
            error('Vivaldi:BridgeAction', 'Thao tác bridge không hợp lệ.');
    end
end

function job = generate(mode, cfg, p)
    mode = lower(char(mode));
    assert(ismember(mode, {'connect', 'update', 'validate', 'simulate'}), 'Vivaldi:BridgeMode', 'Mode không hợp lệ.');
    [ok, e] = vivaldiValidateParams(p);
    assert(ok, 'Vivaldi:InvalidParameters', '%s', strjoin(e, newline));
    assert(isfolder(cfg.outputDir), 'Vivaldi:OutputDirectory', 'Thư mục kết quả không tồn tại.');
    job = struct('mode', mode, 'script', '', 'status', '', 'console', '', 'output', '', 'process', []);
    base = tempname(cfg.outputDir);
    job.script = [base '.vbs'];
    job.status = [base '.status'];
    job.console = [base '.console.log'];
    if ~strcmp(mode, 'connect')
        assert(isfile(cfg.input), 'Vivaldi:InputProject', 'Không tìm thấy dự án đầu vào.');
        assert(~isfile([cfg.input '.lock']), 'Vivaldi:ProjectLocked', ...
               'Dự án đầu vào đang khóa. Đóng dự án trong HFSS trước; không xóa file lock tùy tiện.');
        assert(isfield(cfg, 'design') && ~isempty(cfg.design), 'Vivaldi:Design', 'Chọn design rõ ràng.');
        if strcmp(mode, 'update')
            [~, name, ext] = fileparts(cfg.outputName);
            assert(strcmp(ext, '.aedt') && strcmp([name ext], cfg.outputName) && ...
                   isempty(regexp(name, '[<>:"/\\|?*\x00-\x1f]', 'once')) && ~isempty(name), ...
                   'Vivaldi:OutputName', 'Tên file phải là basename .aedt hợp lệ.');
            job.output = fullfile(cfg.outputDir, cfg.outputName);
            assert(~strcmpi(canonical(cfg.input), canonical(job.output)), ...
                   'Vivaldi:OriginalProtection', 'Đầu ra không được trùng file gốc.');
            assert(~isfile(job.output) && ~isfile([job.output '.lock']), ...
                   'Vivaldi:ExistingOutput', 'File kết quả đã tồn tại hoặc bị khóa; chọn tên mới.');
            sourceParams = verifyExpressions(cfg.input, cfg.design);
            if p.thickness ~= sourceParams.thickness
                source = fileread(cfg.input);
                mid = regexp(source, '(?s)Name=''cable_mid_1''.*?\$end ''GeometryPart''', 'match', 'once');
                assert(isempty(regexp(mid, '(?:YTranslate|MoveVectorY|TranslateVectorY)=''2mm''', 'once')), ...
                       'Vivaldi:UnlinkedSourceHistory', ...
                       'Source has a literal 2mm mid-cutter move. Use Build Antenna for a thickness change.');
            end
        else
            % Validation and solving use the last generated copy, never the source.
            assert(isfield(cfg, 'original') && ~strcmpi(canonical(cfg.original), canonical(cfg.input)), ...
                   'Vivaldi:OriginalProtection', 'Chỉ validate/mô phỏng bản sao đã cập nhật.');
            job.output = cfg.input;
        end
    end
    L = { ...
         'Option Explicit', ...
         'Dim fs, statusPath, oApp, oDesktop, oProject, oDesign, oEditor, oBoundary, oAnalysis', ...
         'Dim beforeObjects, beforeBounds, beforePorts, beforeSetups, beforeCS, beforeMaterials', ...
         'Dim a, b, n, rc, data, vals, report, item', ...
         'Set fs = CreateObject("Scripting.FileSystemObject")', ...
         ['statusPath = ' quote(job.status)], ...
         'Sub Note(msg)', ...
         '  Dim f', ...
         '  Set f = fs.OpenTextFile(statusPath, 8, True, -1)', ...
         '  f.WriteLine CStr(Now) & "|" & msg', ...
         '  f.Close', ...
         'End Sub', ...
         'Sub State(name, msg)', ...
         '  Dim f', ...
         '  Set f = fs.OpenTextFile(statusPath, 8, True, -1)', ...
         '  f.WriteLine "STATE|" & name & "|" & CStr(Now) & "|" & msg', ...
         '  f.Close', ...
         'End Sub', ...
         'Function Check(label)', ...
         '  Dim message', ...
         '  Check = True', ...
         '  If Err.Number <> 0 Then', ...
         '    message = label & ": " & CStr(Err.Number) & " " & Err.Description', ...
         '    Err.Clear', ...
         '    State "FAILED", message', ...
         '    Check = False', ...
         '  End If', ...
         'End Function', ...
         'Function Flat(values)', ...
         '  Dim v, result', ...
         '  result = ""', ...
         '  For Each v In values', ...
         '    result = result & "|" & CStr(v)', ...
         '  Next', ...
         '  Flat = result', ...
         'End Function', ...
         'Function SameFolder(path1, path2)', ...
         '  Dim p1, p2', ...
         '  p1 = LCase(fs.GetAbsolutePathName(path1))', ...
         '  p2 = LCase(fs.GetAbsolutePathName(path2))', ...
         '  Do While Right(p1, 1) = "\"', ...
         '    p1 = Left(p1, Len(p1) - 1)', ...
         '  Loop', ...
         '  Do While Right(p2, 1) = "\"', ...
         '    p2 = Left(p2, Len(p2) - 1)', ...
         '  Loop', ...
         '  SameFolder = (p1 = p2)', ...
         'End Function', ...
         'Function Objects()', ...
         '  Objects = Flat(oEditor.GetObjectsInGroup("Solids")) & ";" & Flat(oEditor.GetObjectsInGroup("Sheets"))', ...
         'End Function', ...
         'Function Materials()', ...
         '  Dim v, result', ...
         '  result = ""', ...
         '  For Each v In oEditor.GetObjectsInGroup("Solids")', ...
         '    result = result & "|" & CStr(v) & "=" & oEditor.GetPropertyValue("Geometry3DAttributeTab", CStr(v), "Material")', ...
         '  Next', ...
         '  Materials = result', ...
         'End Function', ...
         'Function Require(condition, message)', ...
         '  Require = condition', ...
         '  If Not condition Then', ...
         '    State "FAILED", message', ...
         '  End If', ...
         'End Function', ...
         'Sub Main()', ...
         '  On Error Resume Next', ...
         '  State "STARTING", "HFSS Automation starting"', ...
         '  Set oApp = CreateObject("Ansoft.ElectronicsDesktop.2021.2")', ...
         '  Check "CreateObject / license"', ...
         '  Set oDesktop = oApp.GetAppDesktop()', ...
         '  Check "GetAppDesktop"', ...
         '  a = oDesktop.GetVersion()', ...
         '  Check "GetVersion"', ...
         '  Require InStr(1, CStr(a), "2021.2", vbTextCompare) = 1, "HFSS version mismatch; expected 2021 R2"', ...
         '  State "CONNECTED", "Version " & CStr(a)'};
    if ~strcmp(mode, 'connect')
        % CONNECTED is intermediate for project actions; GUI accounts for mode.
        L = [L, { ...
                 '  State "OPENING", "Opening selected project"', ...
                 ['  oDesktop.OpenProject ' quote(cfg.input)], ...
                 '  Check "OpenProject"', ...
                 '  Set oProject = oDesktop.GetActiveProject()', ...
                 '  Check "GetActiveProject"', ...
                 '  a = oProject.GetName()', ...
                 '  Check "Active project identity"', ...
                 ['  Require LCase(CStr(a)) = LCase(fs.GetBaseName(' quote(cfg.input) ')), "Active project does not match selected input"'], ...
                 ['  Set oDesign = oProject.SetActiveDesign(' quote(cfg.design) ')'], ...
                 '  Check "SetActiveDesign"', ...
                 '  Set oEditor = oDesign.SetActiveEditor("3D Modeler")', ...
                 '  Set oBoundary = oDesign.GetModule("BoundarySetup")', ...
                 '  Set oAnalysis = oDesign.GetModule("AnalysisSetup")', ...
                 '  Check "Model modules"', ...
                 '  beforeObjects = Objects()', ...
                 '  Check "Read objects"', ...
                 '  beforeMaterials = Materials()', ...
                 '  Check "Read materials"', ...
                 '  beforeBounds = Flat(oBoundary.GetBoundaries())', ...
                 '  Check "Read boundaries"', ...
                 '  a = oBoundary.GetExcitations()', ...
                 '  Check "Read excitations"', ...
                 '  beforePorts = Flat(a)', ...
                 '  beforeSetups = Flat(oAnalysis.GetSetups())', ...
                 '  Check "Read setups"', ...
                 '  beforeCS = Flat(oEditor.GetCoordinateSystems())', ...
                 '  Check "Inventory before operation"', ...
                 '  Require UBound(a) - LBound(a) + 1 = 4, "Expected exactly two excitations"', ...
                 '  Require CStr(a(1)) = "Lumped Port" And CStr(a(3)) = "Lumped Port", "Expected two Lumped Ports"', ...
                 '  Require InStr(beforeBounds, "Radiation") > 0, "Expected Radiation boundary not found"', ...
                 '  Note "OBJECTS " & beforeObjects', ...
                 '  Note "BOUNDARIES " & beforeBounds', ...
                 '  Note "PORTS " & beforePorts', ...
                 '  Note "SETUPS " & beforeSetups', ...
                 '  Note "CS " & beforeCS', ...
                 '  Note "MATERIALS " & beforeMaterials'}];
        if strcmp(mode, 'update')
            L = [L, {['  Require Not fs.FileExists(' quote(job.output) '), "Output already exists"'], ...
                     ['  oProject.SaveAs ' quote(job.output) ', False'], ...
                     '  Check "SaveAs before modifying variables"', ...
                     ['  Require fs.FileExists(' quote(job.output) '), "SaveAs did not create the requested copy"'], ...
                     '  a = oProject.GetName()', ...
                     '  Check "Read copied project name"', ...
                     ['  Require LCase(CStr(a)) = LCase(fs.GetBaseName(' quote(job.output) ')), "SaveAs project name mismatch"'], ...
                     '  a = oProject.GetPath()', ...
                     '  Check "Read copied project path"', ...
                     ['  Require SameFolder(CStr(a), fs.GetParentFolderName(' quote(job.output) ')), "SaveAs project directory mismatch"'], ...
                     '  Check "Copy identity before modifying variables"', ...
                     '  State "UPDATING", "Copy saved; updating independent variables"'}];
            [defaults, meta] = vivaldiDefaultParams(); %#ok<ASGLU>
            for k = 1:numel(meta)
                n = meta(k).name;
                if p.(n) == sourceParams.(n)
                    continue
                end
                % Log COM baseline and update only literals that differ.
                val = sprintf('%.15g%s', p.(n), meta(k).unit);
                L = [L, {['  a = oDesign.GetVariableValue(' quote(n) ')'], ...
                         ['  Check ' quote(['Read variable ' n])], ...
                         ['  Note ' quote(['VARIABLE ' n ' before=']) ' & CStr(a) & ' quote([' after=' val])], ...
                         ['  If CStr(a) <> ' quote(val) ' Then'], ...
                         ['    oDesign.ChangeProperty Array("NAME:AllTabs", Array("NAME:LocalVariableTab", Array("NAME:PropServers", "LocalVariables"), Array("NAME:ChangedProps", Array(' quote(['NAME:' n]) ', "Value:=", ' quote(val) '))))'], ...
                         ['    Check ' quote(['ChangeProperty ' n])], ...
                         '  End If'}]; %#ok<AGROW>
            end
            L = [L, { ...
                     '  a = Objects()', ...
                     '  Check "Read updated objects"', ...
                     '  Require a = beforeObjects, "Object inventory changed unexpectedly"', ...
                     '  a = Materials()', ...
                     '  Check "Read updated materials"', ...
                     '  Require a = beforeMaterials, "Materials changed unexpectedly"', ...
                     '  a = Flat(oBoundary.GetBoundaries())', ...
                     '  Check "Read updated boundaries"', ...
                     '  Require a = beforeBounds, "Boundaries changed unexpectedly"', ...
                     '  a = Flat(oBoundary.GetExcitations())', ...
                     '  Check "Read updated ports"', ...
                     '  Require a = beforePorts, "Ports changed unexpectedly"', ...
                     '  a = Flat(oAnalysis.GetSetups())', ...
                     '  Check "Read updated setups"', ...
                     '  Require a = beforeSetups, "Solution setups changed unexpectedly"', ...
                     '  a = Flat(oEditor.GetCoordinateSystems())', ...
                     '  Check "Read updated coordinate systems"', ...
                     '  Require a = beforeCS, "Coordinate systems changed unexpectedly"', ...
                     '  a = Flat(oEditor.GetObjectsInGroup("Unclassified"))', ...
                     '  Check "Read Unclassified group"', ...
                     '  Require a = "", "Unclassified geometry after update"', ...
                     '  Check "Inventory after update"', ...
                     '  oProject.Save', ...
                     '  Check "Save updated copy"', ...
                     ['  Require fs.FileExists(' quote(job.output) '), "Saved output missing"'], ...
                     '  Note "Inventory preserved; port face attachment, integration lines and intersections still require model validation."', ...
                     '  State "UPDATED", "Updated copy saved; simulation not run"'}];
        elseif strcmp(mode, 'validate')
            L = [L, { ...
                     '  State "VALIDATING", "Calling ValidateDesign"', ...
                     ['  rc = oDesign.ValidateDesign(' quote([base '.validation.log']) ')'], ...
                     '  If Err.Number <> 0 Then', ...
                     '    Note "ValidateDesign unsupported or failed: " & Err.Description', ...
                     '    Err.Clear', ...
                     '    State "VALIDATION_UNVERIFIED", "Inspect model manually in HFSS"', ...
                     '  ElseIf Not IsNumeric(rc) Then', ...
                     '    State "VALIDATION_UNVERIFIED", "Unknown ValidateDesign result"', ...
                     '  ElseIf CLng(rc) = 1 Then', ...
                     '    Note "ValidateDesign raw return=" & CStr(rc)', ...
                     '    State "VALIDATED", "ValidateDesign returned success code 1; inspect validation report"', ...
                     '  Else', ...
                     '    State "FAILED", "HFSS validation returned failure code " & CStr(rc)', ...
                     '  End If'}];
        else
            L = [L, { ...
                     '  State "RUNNING", "Analyze Setup1 started by explicit user action"', ...
                     '  oDesign.Analyze "Setup1"', ...
                     '  Check "Analyze Setup1"', ...
                     '  oProject.Save', ...
                     '  Check "Save after solve"', ...
                     '  State "CHECKING_RESULTS", "Analyze Setup1 returned; checking actual solution data"', ...
                     '  rc = False', ...
                     '  Set report = oDesign.GetModule("ReportSetup")', ...
                     '  a = oAnalysis.GetSetups()', ...
                     '  b = oAnalysis.GetSweeps(CStr(a(0)))', ...
                     '  data = report.GetSolutionDataPerVariation("Modal Solution Data", CStr(a(0)) & " : " & CStr(b(0)), Array(), Array("Freq:=", Array("All")), Array("dB(S(1,1))", "dB(S(2,2))"))', ...
                     '  If Err.Number <> 0 Then', ...
                     '    Note "Result verification failed: " & Err.Description', ...
                     '    Err.Clear', ...
                     '  Else', ...
                     '    Set item = data(0)', ...
                     '    vals = item.GetRealDataValues("dB(S(1,1))")', ...
                     '    If Err.Number = 0 Then', ...
                     '      Require UBound(vals) >= 0, "No S11 samples"', ...
                     '      vals = item.GetRealDataValues("dB(S(2,2))")', ...
                     '      Check "S22 solution samples"', ...
                     '      Require UBound(vals) >= 0, "No S22 samples"', ...
                     '      State "SIMULATED", "Analyze Setup1 returned with S11/S22 samples; inspect convergence and sweep completeness in HFSS"', ...
                     '      rc = True', ...
                     '    Else', ...
                     '      Note "Solution samples unavailable: " & Err.Description', ...
                     '      Err.Clear', ...
                     '    End If', ...
                     '  End If', ...
                     '  If Not rc Then State "SOLVE_RETURNED_UNVERIFIED", "Analyze Setup1 returned but result verification is unavailable"'}];
        end
        L = [L, { ...
                 '  oDesktop.CloseProject oProject.GetName()', ...
                 '  If Err.Number <> 0 Then', ...
                 '    Note "Could not close project: " & Err.Description', ...
                 '    Err.Clear', ...
                 '  End If'}];
    end
    L = [L, {'End Sub', 'Main'}];
    % Each failing guard exits Main. Raising inside On Error Resume Next would
    % merely resume at the next mutation, so guards explicitly return booleans.
    for k = 1:numel(L)
        line = strtrim(L{k});
        if startsWith(line, 'Check ')
            L{k} = ['  If Not Check(' line(7:end) ') Then Exit Sub'];
        elseif startsWith(line, 'Require ')
            L{k} = ['  If Not Require(' line(9:end) ') Then Exit Sub'];
        end
    end
    HFSSRuntimeSupport.writeUTF16(job.script, sprintf('%s\r\n', L{:}));
end

function sourceParams = verifyExpressions(path, design)
    info = vivaldiInspectProject(path, design);
    assert(numel(info.designs) == 1 && strcmp(info.designs{1}, design), ...
           'Vivaldi:ProjectDesign', 'Chỉ hỗ trợ dự án một HFSS design đã kiểm tra.');
    [p, ~] = vivaldiDefaultParams();
    names = fieldnames(p);
    sourceParams = p;
    for k = 1:numel(names)
        idx = find(strcmp(info.variables(:, 1), names{k}));
        assert(numel(idx) == 1, 'Vivaldi:VariableSchema', 'Biến %s thiếu hoặc không duy nhất.', names{k});
        unit = 'mm';
        if strcmp(names{k}, 'deg_slot_t')
            unit = 'deg';
        end
        token = regexp(strtrim(info.variables{idx, 2}), ...
                       ['^([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)\s*' unit '$'], 'tokens', 'once');
        assert(~isempty(token), 'Vivaldi:IndependentFormula', ...
               'Biến %s không phải literal %s; không ghi đè công thức nguồn.', names{k}, unit);
        sourceParams.(names{k}) = str2double(token{1});
    end
    expected = { ...
                'slot_t_L', '6.4mm+them'; ...
                'L_flare', 'L_flare_1+slot_t_L'; ...
                'r_flare', '(1/L_flare)*ln(aperture_w/slot_feed_w)'; ...
                'z_feed', '((slot_feed_w/2)*exp((slot_t_L)*r_flare) +slot_feed_w/2)*sin(deg_slot_t)+slot_t_L*(1-cos(deg_slot_t))'; ...
                'x_feed', '((slot_feed_w/2)*exp((slot_t_L)*r_flare) +slot_feed_w/2)*cos(deg_slot_t)+slot_t_L*(sin(deg_slot_t))-(slot_feed_w/2)*exp((slot_t_L)*r_flare)'; ...
                'L_patch', 'L_flare_1+slot_t_L-z_feed+h3_slot_feed+slot_feed_w+h_de'; ...
                'h_cabin', 'h_de+slot_feed_w'; 'h_cabout', 'h_cabin-slot_feed_w'; ...
                'h_cabmid', 'h_cabin-slot_feed_w'; 'de_L', 'aperture_w+thickness'; 'de_W', 'aperture_w+thickness'};
    for k = 1:size(expected, 1)
        idx = find(strcmp(info.variables(:, 1), expected{k, 1}));
        assert(numel(idx) == 1 && strcmp(regexprep(info.variables{idx, 2}, '\s', ''), ...
                                         regexprep(expected{k, 2}, '\s', '')), 'Vivaldi:FormulaMismatch', ...
               'Công thức %s khác mô hình tham chiếu. Không cập nhật tự động; cần phân tích phiên bản này.', expected{k, 1});
    end
end

function s = quote(s)
    s = char(s);
    assert(~any(s == char(10) | s == char(13) | s == char(0)), ...
           'Vivaldi:ScriptString', 'Chuỗi script chứa ký tự điều khiển.');
    s = ['"' strrep(s, '"', '""') '"'];
end

function path = canonical(path)
    path = char(java.io.File(path).getCanonicalPath());
end

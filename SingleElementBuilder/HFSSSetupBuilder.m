function info = HFSSSetupBuilder(w,p,cfg)
%HFSSSETUPBUILDER Emit source-derived ports, open region and solver setups.
% This generates Automation commands; it does not claim HFSS execution.
% Source: MODEL_RECONSTRUCTION_SPEC.md sections 6--9, AEDT 17_10_2026.
if nargin<3, cfg=struct(); end
if nargin<2, p=struct(); end %#ok<NASGU>
profile=getfielddefault(cfg,'profile','Original');
assert(any(strcmp(profile,{'Original','QuickTest'})), ...
    'VivaldiBuilder:Profile','profile must be Original or QuickTest.');
excited=getfielddefault(cfg,'excitedPort',1);
assert(isnumeric(excited)&&isscalar(excited)&&any(excited==[1 2]), ...
    'VivaldiBuilder:Excitation','Choose exactly one excited port (1 or 2).');
study=getfielddefault(cfg,'studyBand',[]);
assert(isempty(study)||(isnumeric(study)&&numel(study)==2&& ...
    all(isfinite(study))&&study(1)>0&&study(2)>study(1)), ...
    'VivaldiBuilder:StudyBand','studyBand must be empty or [start stop] in GHz.');
info=struct('originalSetup','Setup1','runSetup','Setup1','sweep','Sweep', ...
    'solution','Setup1 : Sweep','status','Commands generated; HFSS not yet executed');
w.declare('Dim sbrVerified, sbrMesh');
w.helper({ ...
    'Function SBRPairExists(values, wantedName, wantedType)', ...
    '  Dim i', ...
    '  SBRPairExists = False', ...
    '  If Not IsArray(values) Then Exit Function', ...
    '  For i = LBound(values) To UBound(values) - 1 Step 2', ...
    '    If CStr(values(i)) = wantedName And CStr(values(i+1)) = wantedType Then SBRPairExists = True', ...
    '  Next', ...
    'End Function', ...
    'Function SBRExactlyTwoPorts()', ...
    '  Dim values', ...
    '  values = oBoundary.GetExcitations()', ...
    '  SBRExactlyTwoPorts = False', ...
    '  If Not IsArray(values) Then Exit Function', ...
    '  If UBound(values) - LBound(values) + 1 <> 4 Then Exit Function', ...
    '  SBRExactlyTwoPorts = SBRPairExists(values, "1", "Lumped Port") And SBRPairExists(values, "2", "Lumped Port")', ...
    'End Function'});
w.stage('Assign Ports');
w.call('oEditor.SetWCS Array("NAME:SetWCS Parameter", "Working Coordinate System:=", "Global", "RegionDepCSOk:=", False)', ...
    'Set Global CS for coordinate-defined integration lines');
% Boundary names 1/2 are distinct from the sheets port1/port2. No old IDs.
c='-x_feed-positionx+slot_feed_w+h2';
z='z_feed-h3_slot_feed-h_cabin';
c2='(aperture_w+thickness)/2';
y2='(aperture_w+thickness)/2+x_feed+positionx-slot_feed_w-h2';
assignport(w,'1','port1',{[c '-r_cabmid'],'0mm',z},{[c '-r_cabin'],'0mm',z});
assignport(w,'2','port2',{c2,[y2 '+r_cabmid'],z},{c2,[y2 '+r_cabin'],z});
w.call('Note "Integration lines: radial outer-to-inner, port1 -X / port2 +Y; source EdgeCenter azimuth inferred. Verify port field phase in HFSS."', ...
    'Record integration-line provenance and runtime limitation');
w.call('Note "Assigned two 50ohm modes. Port attachment/contact and source phase require HFSS geometry and port-field checks."', ...
    'Record remaining port validation');
w.call('sbrVerified = SBRExactlyTwoPorts()', 'Read back exactly two lumped excitations');
w.require('sbrVerified', 'Expected exactly two Lumped Ports named 1 and 2');
power={'0W','0W'}; power{excited}='1W';
w.call(['oSolutions.EditSources Array(Array("IncludePortPostProcessing:=", False, "SpecifySystemPower:=", False), ' ...
    'Array("Name:=", "1:1", "Magnitude:=", ' w.q(power{1}) ', "Phase:=", "0deg"), ' ...
    'Array("Name:=", "2:1", "Magnitude:=", ' w.q(power{2}) ', "Phase:=", "0deg"))'], ...
    sprintf('Set port %d = 1W, other port = 0W, both phase 0deg',excited));

w.stage('Create Open Region');
region={'"NAME:RegionParameters"'};
for axis={'+X','-X','+Y','-Y','+Z','-Z'}
    region=[region,{w.q([axis{1} 'PaddingType:=']),'"Absolute Offset"', ...
        w.q([axis{1} 'Padding:=']),'"20mm"'}]; %#ok<AGROW>
end
attrs=['Array("NAME:Attributes", "Name:=", "RadiatingSurface", "Flags:=", "Wireframe#", ' ...
    '"Color:=", "(255 0 0)", "Transparency:=", 0, "PartCoordinateSystem:=", "Global", ' ...
    '"MaterialValue:=", ' w.q('"vacuum"') ', "SolveInside:=", True)'];
w.call(['oEditor.CreateRegion Array(' strjoin(region,', ') '), ' attrs], ...
    'Create RadiatingSurface in Global with six absolute 20mm paddings');
w.call(['oBoundary.AssignRadiation Array("NAME:Open1", "Objects:=", Array("RadiatingSurface"), ' ...
    '"IsFssReference:=", False, "IsForPML:=", False)'], 'Assign Open1 Radiation to RadiatingSurface');
w.call('sbrVerified = SBRPairExists(oBoundary.GetBoundaries(), "Open1", "Radiation")', ...
    'Read back Open1 Radiation boundary');
w.require('sbrVerified', ...
    'Open1 Radiation boundary was not found after assignment');

w.stage('Create Solution');
w.call('Set sbrMesh = oDesign.GetModule("MeshSetup")','Get MeshSetup for source initial mesh');
w.call(['sbrMesh.InitialMeshSettings Array("NAME:MeshSettings", ' ...
    'Array("NAME:GlobalSurfApproximation", "CurvedSurfaceApproxChoice:=", "UseSlider", "SliderMeshSettings:=", 5), ' ...
    'Array("NAME:GlobalCurvilinear", "Apply:=", False), ' ...
    'Array("NAME:GlobalModelRes", "UseAutoLength:=", True), "MeshMethod:=", "Auto", ' ...
    '"UseLegacyFaceterForTauVolumeMesh:=", False, "DynamicSurfaceResolution:=", False, ' ...
    '"UseFlexMeshingForTAUvolumeMesh:=", False, "UseAlternativeMeshMethodsAsFallBack:=", True, ' ...
    '"AllowPhiForLayeredGeometry:=", True)'], 'Apply source initial mesh slider 5 and mesh flags');
createsetup(w,'Setup1',5,.02,5,50,3);
createsweep(w,'Setup1',5,20,.25);
if strcmp(profile,'QuickTest')
    createsetup(w,'QuickTest',5,.1,1,3,1);
    createsweep(w,'QuickTest',5,20,5);
    info.runSetup='QuickTest';
    w.call('Note "QuickTest: 3 adaptive passes maximum, deltaS 0.1, coarse 5GHz sweep. It does not replace the Original Setup1 solution."', ...
        'Describe QuickTest accuracy limitation');
end
if ~isempty(study)
    createsetup(w,'StudyBand1',study(1),.02,5,50,3);
    createsweep(w,'StudyBand1',study(1),study(2),.25);
    if strcmp(profile,'Original'), info.runSetup='StudyBand1'; end
end
if isfield(cfg,'runSetup') && ~isempty(cfg.runSetup), info.runSetup=char(cfg.runSetup); end
info.solution=[info.runSetup ' : Sweep'];

% Actual Automation method is InsertInfiniteSphereSetup. No array is created.
sphere(w,'3D',{'0deg','180deg','2deg','-180deg','180deg','2deg'});
sphere(w,'Elevation',{'-180deg','180deg','1deg','0deg','90deg','90deg'});
sphere(w,'Azimuth',{'90deg','90deg','0deg','-180deg','180deg','1deg'});
w.call('Note "Single-element design: no array or array-factor operation emitted. Verify saved RadField.ArraySetup UseOption=NoArray during acceptance."', ...
    'Record NoArray acceptance check');
end

function assignport(w,name,sheet,start,finish)
xyz=@(v) ['Array(' strjoin(cellfun(@(t)w.q(t),v,'UniformOutput',false),', ') ')'];
statement=['oBoundary.AssignLumpedPort Array(' w.q(['NAME:' name]) ...
    ', "Objects:=", Array(' w.q(sheet) '), "DoDeembed:=", False, "RenormalizeAllTerminals:=", True, ' ...
    'Array("NAME:Modes", Array("NAME:Mode1", "ModeNum:=", 1, "UseIntLine:=", True, ' ...
    'Array("NAME:IntLine", "Start:=", ' xyz(start) ', "End:=", ' xyz(finish) '), ' ...
    '"AlignmentGroup:=", 0, "CharImp:=", "Zpi", "RenormImp:=", "50ohm")), ' ...
    '"ShowReporterFilter:=", False, "ReporterFilter:=", Array(True), "Impedance:=", "50ohm")'];
w.call(statement,['Assign 50ohm Lumped Port ' name ' to ' sheet]);
end

function createsetup(w,name,freq,delta,minpass,maxpass,converged)
% Single adaptive frequency uses the supported 2021-era API fields rather
% than assuming serialization-only SolveType is an Automation parameter.
statement=sprintf(['oAnalysis.InsertSetup "HfssDriven", Array(%s, "AdaptMultipleFreqs:=", False, "PortsOnly:=", False, ' ...
    '"Frequency:=", "%0.15gGHz", "MaxDeltaS:=", %0.15g, "UseMatrixConv:=", False, ' ...
    '"MaximumPasses:=", %d, "MinimumPasses:=", %d, "MinimumConvergedPasses:=", %d, ' ...
    '"PercentRefinement:=", 10, "IsEnabled:=", True, Array("NAME:MeshLink", "ImportMesh:=", False), ' ...
    '"BasisOrder:=", 1, "DoLambdaRefine:=", True, "DoMaterialLambda:=", True, ' ...
    '"SetLambdaTarget:=", False, "Target:=", 0.3333, "UseMaxTetIncrease:=", False, ' ...
    '"PortAccuracy:=", 2, "UseABCOnPort:=", False, "SetPortMinMaxTri:=", False, ' ...
    '"UseDomains:=", False, "UseIterativeSolver:=", False, "SaveRadFieldsOnly:=", False, ' ...
    '"SaveAnyFields:=", True, "IESolverType:=", "Auto", "LambdaTargetForIESolver:=", 0.15, ' ...
    '"UseDefaultLambdaTgtForIESolver:=", True, "IE Solver Accuracy:=", "Balanced")'], ...
    w.q(['NAME:' name]),freq,delta,maxpass,minpass,converged);
w.call(statement,['Insert independent solver ' name]);
end

function createsweep(w,setup,first,last,step)
w.call(sprintf(['oAnalysis.InsertFrequencySweep %s, Array("NAME:Sweep", "IsEnabled:=", True, ' ...
    '"RangeType:=", "LinearStep", "RangeStart:=", "%0.15gGHz", "RangeEnd:=", "%0.15gGHz", ' ...
    '"RangeStep:=", "%0.15gGHz", "Type:=", "Discrete", "SaveFields:=", True, "SaveRadFields:=", True)'], ...
    w.q(setup),first,last,step), ['Insert Discrete Sweep for ' setup]);
end

function sphere(w,name,values)
keys={'ThetaStart','ThetaStop','ThetaStep','PhiStart','PhiStop','PhiStep'};
args={w.q(['NAME:' name]),'"UseCustomRadiationSurface:="','False', ...
    '"CSDefinition:="','"Theta-Phi"','"Polarization:="','"Linear"'};
for k=1:numel(keys), args=[args,{w.q([keys{k} ':=']),w.q(values{k})}]; end %#ok<AGROW>
args=[args,{'"UseLocalCS:="','False'}];
w.call(['oRadField.InsertInfiniteSphereSetup Array(' strjoin(args,', ') ')'], ...
    ['Insert Global far-field sphere ' name]);
end

function value=getfielddefault(s,name,fallback)
if isfield(s,name)&&~isempty(s.(name)), value=s.(name); else, value=fallback; end
end

classdef HFSSSetupBuilder
    methods (Static)
        function build(w,cfg)
            w.stage('Create Open Region');
            HFSSGeometryBuilder.wcs(w,'RelativeCS1');
            region = {'NAME:RegionParameters'};
            directions = {'+X','-X','+Y','-Y','+Z','-Z'};
            for k = 1:6
                region = [region {[directions{k} 'PaddingType:='],'Absolute Offset', ...
                    [directions{k} 'Padding:='],'20mm'}]; %#ok<AGROW>
            end
            attrs = HFSSScript.attributes('RadiatingSurface','vacuum','RelativeCS1',true);
            attrs{find(strcmp(attrs,'Flags:='))+1} = 'Wireframe#';
            w.api('oEditor','CreateRegion',region,attrs);
            w.api('oBoundary','AssignRadiation',{'NAME:Open1','Objects:=',{'RadiatingSurface'}, ...
                'IsIncidentField:=',false,'IsEnforcedField:=',false,'IsFssReference:=',false, ...
                'IsForPML:=',false});
            HFSSGeometryBuilder.wcs(w,'Global');
            w.stage('Create Solution');
            HFSSSetupBuilder.solution(w,'Setup1',false,cfg);
            HFSSSetupBuilder.solution(w,'QuickTest',true,cfg);
            spheres = {'3D',0,180,2,-180,180,2; ...
                'Elevation',-180,180,1,0,90,90;'Azimuth',90,90,0,-180,180,1};
            for k = 1:3
                vals = cellfun(@(n)sprintf('%gdeg',n),spheres(k,2:7),'UniformOutput',false);
                w.api('oRad','InsertFarFieldSphereSetup',{['NAME:' spheres{k,1}], ...
                    'UseCustomRadiationSurface:=',false,'CSDefinition:=','Theta-Phi', ...
                    'Polarization:=','Linear','ThetaStart:=',vals{1},'ThetaStop:=',vals{2}, ...
                    'ThetaStep:=',vals{3},'PhiStart:=',vals{4},'PhiStop:=',vals{5}, ...
                    'PhiStep:=',vals{6},'UseLocalCS:=',false});
            end
            % New DrivenModal designs default to NoArray; no array API is invoked.
            HFSSSetupBuilder.sources(w,cfg.port);
        end
        function solution(w,name,quick,cfg)
            delta = .02; minimum = 5; maximum = 50; converged = 3;
            if quick, delta = .1; minimum = 1; maximum = 6; converged = 1; end
            w.api('oAnalysis','InsertSetup','HfssDriven',{['NAME:' name], ...
                'SolveType:=','Single','Frequency:=','5GHz','MaxDeltaS:=',delta, ...
                'UseMatrixConv:=',false,'MaximumPasses:=',maximum,'MinimumPasses:=',minimum, ...
                'MinimumConvergedPasses:=',converged,'PercentRefinement:=',10, ...
                'IsEnabled:=',true,{'NAME:MeshLink','ImportMesh:=',false}, ...
                'BasisOrder:=',1,'DoLambdaRefine:=',true,'DoMaterialLambda:=',true, ...
                'SetLambdaTarget:=',false,'Target:=',.3333,'UseMaxTetIncrease:=',false, ...
                'PortAccuracy:=',2,'UseABCOnPort:=',false,'SetPortMinMaxTri:=',false, ...
                'PortMinTri:=',100,'PortMaxTri:=',500,'UseDomains:=',false, ...
                'UseIterativeSolver:=',false,'EnhancedLowFreqAccuracy:=',false, ...
                'SaveRadFieldsOnly:=',false,'SaveAnyFields:=',true,'IESolverType:=','Auto', ...
                'LambdaTargetForIESolver:=',.15,'UseDefaultLambdaTgtForIESolver:=',true, ...
                'IE Solver Accuracy:=','Balanced'});
            HFSSSetupBuilder.sweep(w,name,quick,cfg,false);
        end
        function sweep(w,name,quick,cfg,editExisting)
            start = 5; stop = 20; step = .25;
            if quick, start = cfg.fStart; stop = cfg.fStop; step = cfg.fStep; end
            parameters = {'NAME:Sweep','IsEnabled:=',true, ...
                'RangeType:=','LinearStep','RangeStart:=',sprintf('%gGHz',start), ...
                'RangeEnd:=',sprintf('%gGHz',stop),'RangeStep:=',sprintf('%gGHz',step), ...
                'Type:=','Discrete','SaveFields:=',true,'SaveRadFields:=',true};
            if editExisting
                w.api('oAnalysis','EditFrequencySweep',name,'Sweep',parameters);
            else
                w.api('oAnalysis','InsertFrequencySweep',name,parameters);
            end
        end
        function sources(w,port)
            p1 = '1W'; p2 = '0W'; if port == 2, p1 = '0W'; p2 = '1W'; end
            w.api('oSolutions','EditSources',{{'IncludePortPostProcessing:=',true,'SpecifySystemPower:=',false}, ...
                {'Name:=','1:1','Magnitude:=',p1,'Phase:=','0deg'}, ...
                {'Name:=','2:1','Magnitude:=',p2,'Phase:=','0deg'}});
        end
    end
end

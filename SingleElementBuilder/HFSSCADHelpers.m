function lines = HFSSCADHelpers()
%HFSSCADHELPERS VBScript runtime helpers shared by scratch CAD and readback.
% No guessed clone suffixes, retained model cutters, or suppressed COM errors.
% A caller must invoke helpers through HFSSScriptWriter.call so any COM error
% propagates to that one operation's error guard and recovery save.
lines = {
'Function BuilderObjectNames()'
'  Dim names, groupName, objects, objectName'
'  Set names = CreateObject("Scripting.Dictionary")'
'  names.CompareMode = 1'
'  For Each groupName In Array("Solids", "Sheets", "Lines", "Unclassified")'
'    objects = oEditor.GetObjectsInGroup(CStr(groupName))'
'    If IsArray(objects) Then'
'      For Each objectName In objects'
'        names(CStr(objectName)) = True'
'      Next'
'    ElseIf Not IsEmpty(objects) Then'
'      If Not IsNull(objects) Then'
'        If CStr(objects) <> "" Then names(CStr(objects)) = True'
'      End If'
'    End If'
'  Next'
'  BuilderObjectNames = names.Keys'
'End Function'
''
'Function BuilderContainsName(names, target)'
'  Dim candidate'
'  BuilderContainsName = False'
'  If Not IsArray(names) Then Exit Function'
'  For Each candidate In names'
'    If StrComp(CStr(candidate), CStr(target), 1) = 0 Then'
'      BuilderContainsName = True'
'      Exit Function'
'    End If'
'  Next'
'End Function'
''
'Function BuilderGroupCount(groupName)'
'  Dim objects, objectName, count'
'  count = 0'
'  objects = oEditor.GetObjectsInGroup(groupName)'
'  If IsArray(objects) Then'
'    For Each objectName In objects'
'      count = count + 1'
'    Next'
'  ElseIf Not IsEmpty(objects) Then'
'    If Not IsNull(objects) Then'
'      If CStr(objects) <> "" Then count = 1'
'    End If'
'  End If'
'  BuilderGroupCount = count'
'End Function'
''
'Function BuilderFaceCount(objectName)'
'  Dim faces, faceId, count'
'  count = 0'
'  faces = oEditor.GetFaceIDs(objectName)'
'  If Not IsArray(faces) Then Err.Raise vbObjectError + 2101, "BuilderFaceCount", "No face array for " & objectName'
'  For Each faceId In faces'
'    count = count + 1'
'  Next'
'  BuilderFaceCount = count'
'End Function'
''
'Function BuilderVerifyCylinder(objectName, cx, cy, zBottom, zTop, rInner, rOuter)'
'  Dim faces, faceId, area, capArea, outerArea, innerArea, pi, height, tolerance, center'
'  Dim bottomCaps, topCaps, outerWalls, innerWalls'
'  pi = 4 * Atn(1)'
'  height = zTop - zBottom'
'  tolerance = 0.000001'
'  capArea = pi * (rOuter*rOuter - rInner*rInner)'
'  outerArea = 2 * pi * rOuter * height'
'  innerArea = 2 * pi * rInner * height'
'  bottomCaps = 0: topCaps = 0: outerWalls = 0: innerWalls = 0'
'  BuilderVerifyCylinder = False'
'  faces = oEditor.GetFaceIDs(objectName)'
'  For Each faceId In faces'
'    area = CDbl(oEditor.GetFaceArea(faceId))'
'    If Abs(area - capArea) <= tolerance Then'
'      center = oEditor.GetFaceCenter(faceId)'
'      If Not IsArray(center) Then Exit Function'
'      If Abs(CDbl(center(0)) - cx) > tolerance Or Abs(CDbl(center(1)) - cy) > tolerance Then Exit Function'
'      If Abs(CDbl(center(2)) - zBottom) <= tolerance Then'
'        bottomCaps = bottomCaps + 1'
'      ElseIf Abs(CDbl(center(2)) - zTop) <= tolerance Then'
'        topCaps = topCaps + 1'
'      Else'
'        Exit Function'
'      End If'
'    ElseIf Abs(area - outerArea) <= tolerance Then'
'      outerWalls = outerWalls + 1'
'    ElseIf rInner > 0 And Abs(area - innerArea) <= tolerance Then'
'      innerWalls = innerWalls + 1'
'    Else'
'      Exit Function'
'    End If'
'  Next'
'  If bottomCaps <> 1 Or topCaps <> 1 Or outerWalls <> 1 Then Exit Function'
'  If rInner > 0 Then'
'    BuilderVerifyCylinder = (innerWalls = 1)'
'  Else'
'    BuilderVerifyCylinder = (innerWalls = 0)'
'  End If'
'End Function'
''
'Function BuilderVerifyCircularSheet(objectName, cx, cy, cz, radius)'
'  Dim faces, faceId, count, center, area, tolerance'
'  tolerance = 0.000001'
'  BuilderVerifyCircularSheet = False'
'  faces = oEditor.GetFaceIDs(objectName)'
'  count = 0'
'  For Each faceId In faces'
'    count = count + 1'
'    area = CDbl(oEditor.GetFaceArea(faceId))'
'    If Abs(area - 4*Atn(1)*radius*radius) > tolerance Then Exit Function'
'    center = oEditor.GetFaceCenter(faceId)'
'    If Not IsArray(center) Then Exit Function'
'    If Abs(CDbl(center(0)) - cx) > tolerance Or Abs(CDbl(center(1)) - cy) > tolerance Or Abs(CDbl(center(2)) - cz) > tolerance Then Exit Function'
'  Next'
'  BuilderVerifyCircularSheet = (count = 1)'
'End Function'
''
'Function BuilderHasExactlyNames(expected)'
'  Dim actual, name, actualCount, expectedCount'
'  actual = BuilderObjectNames()'
'  actualCount = 0'
'  expectedCount = 0'
'  BuilderHasExactlyNames = False'
'  For Each name In actual'
'    actualCount = actualCount + 1'
'    If Not BuilderContainsName(expected, CStr(name)) Then Exit Function'
'  Next'
'  For Each name In expected'
'    expectedCount = expectedCount + 1'
'    If Not BuilderContainsName(actual, CStr(name)) Then Exit Function'
'  Next'
'  BuilderHasExactlyNames = (actualCount = expectedCount)'
'End Function'
''
'Sub BuilderCloneNamed(sourceName, desiredName, operation)'
'  Dim beforeNames, afterNames, objectName, newName, newCount'
'  beforeNames = BuilderObjectNames()'
'  If Not BuilderContainsName(beforeNames, sourceName) Then Err.Raise vbObjectError + 2102, "BuilderCloneNamed", "Missing clone source: " & sourceName'
'  If BuilderContainsName(beforeNames, desiredName) Then Err.Raise vbObjectError + 2103, "BuilderCloneNamed", "Clone target already exists: " & desiredName'
'  Select Case operation'
'    Case "copy"'
'      oEditor.Copy Array("NAME:Selections", "Selections:=", sourceName)'
'      oEditor.Paste'
'    Case "rotate"'
'      oEditor.DuplicateAroundAxis Array("NAME:Selections", "Selections:=", sourceName, "NewPartsModelFlag:=", "Model"), Array("NAME:DuplicateAroundAxisParameters", "CreateNewObjects:=", True, "WhichAxis:=", "Z", "AngleStr:=", "-90deg", "NumClones:=", "2"), Array("NAME:Options", "DuplicateBoundaries:=", True)'
'    Case Else'
'      Err.Raise vbObjectError + 2104, "BuilderCloneNamed", "Unknown clone operation: " & operation'
'  End Select'
'  afterNames = BuilderObjectNames()'
'  newCount = 0'
'  For Each objectName In afterNames'
'    If Not BuilderContainsName(beforeNames, CStr(objectName)) Then'
'      newName = CStr(objectName)'
'      newCount = newCount + 1'
'    End If'
'  Next'
'  If newCount <> 1 Then Err.Raise vbObjectError + 2105, "BuilderCloneNamed", "Expected exactly one new object from " & sourceName & "; found " & CStr(newCount)'
'  If StrComp(newName, desiredName, 0) <> 0 Then'
'    oEditor.ChangeProperty Array("NAME:AllTabs", Array("NAME:Geometry3DAttributeTab", Array("NAME:PropServers", newName), Array("NAME:ChangedProps", Array("NAME:Name", "Value:=", desiredName))))'
'  End If'
'  If Not BuilderContainsName(BuilderObjectNames(), desiredName) Then Err.Raise vbObjectError + 2106, "BuilderCloneNamed", "Clone rename was not confirmed: " & desiredName'
'End Sub'
};
end

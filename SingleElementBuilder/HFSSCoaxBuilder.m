function HFSSCoaxBuilder(w, p)
%HFSSCOAXBUILDER Two copper coax feeds, circular port sheets, six full cutters.
% HFSSGeometryBuilder installs the VBS runtime helpers and creates the united
% metal body first. Port assignment itself is performed by HFSSSetupBuilder.
% Crucially the outer-cylinder cutter snapshots precede hollowing each coax.
w.stage('Create Coax');
setWCS(w, 'slot_feed_td');
cylinder(w, 'cable_in', '-positionx+slot_feed_w+h2', '-h3_slot_feed', ...
    'r_cabin', '-h_cabin', 'copper', false);
cylinder(w, 'cable_out', '-positionx+h2+slot_feed_w', ...
    '-h3_slot_feed-slot_feed_w', 'r_cabout', '-h_cabout', 'copper', false);
cylinder(w, 'cable_mid', '-positionx+h2+slot_feed_w', ...
    '-h3_slot_feed-slot_feed_w', 'r_cabmid', '-h_cabout', 'vacuum', true);
w.call(['oEditor.CreateCircle Array("NAME:CircleParameters", "IsCovered:=", False, ' ...
    '"XCenter:=", "-positionx+slot_feed_w+h2", "YCenter:=", "0mm", ' ...
    '"ZCenter:=", "-h3_slot_feed-h_cabin", "Radius:=", "r_cabmid", ' ...
    '"WhichAxis:=", "Z", "NumSegments:=", "0"), ' ...
    attributes(w, 'port1', 'slot_feed_td', 'vacuum', true)], 'Create port1 circle wire');
w.call(['oEditor.CoverLines ' selections('port1')], 'CoverLines circular port1');

setWCS(w, 'RelativeCS1');
sources = {'cable_in', 'cable_out', 'cable_mid', 'port1'};
targets = {'cable_in_1', 'cable_out_1', 'cable_mid_1', 'port2'};
for k = 1:numel(sources)
    w.call(['BuilderCloneNamed ' w.q(sources{k}) ', ' w.q(targets{k}) ', "rotate"'], ...
        ['DuplicateAroundAxis ' sources{k} ' -90deg at RelativeCS1']);
    w.call(['oEditor.Move ' selections(targets{k}) ...
        ', Array("NAME:TranslateParameters", "TranslateVectorX:=", "0mm", ' ...
        '"TranslateVectorY:=", "thickness", "TranslateVectorZ:=", "0mm")'], ...
        ['Move ' targets{k} ' by thickness along RelativeCS1 Y']);
end
w.call('Note "Parameterization: cable_mid_1 Move uses thickness (source literal 2mm); equal at defaults, keeps cutters coaxial when thickness changes."', ...
    'Record source literal parameterization');

% Snapshot all six source operands while BOTH cable_out objects are SOLID.
% Copying the finished hollow cable_out would leave aluminum in its bore.
w.stage('Apply Boolean');
cutterSources = {'cable_in', 'cable_in_1', 'cable_mid', ...
    'cable_mid_1', 'cable_out', 'cable_out_1'};
cutters = {'cable_in_2', 'cable_in_1_1', 'cable_mid_2', ...
    'cable_mid_1_1', 'cable_out_2', 'cable_out_1_1'};
for k = 1:numel(cutters)
    w.call(['BuilderCloneNamed ' w.q(cutterSources{k}) ', ' w.q(cutters{k}) ', "copy"'], ...
        ['Snapshot full cylinder cutter ' cutters{k} ' before outer hollowing']);
end
w.require('BuilderFaceCount("cable_out_2") = 3 And BuilderFaceCount("cable_out_1_1") = 3', ...
    'Outer cutters must be full cylinders captured before hollowing');
subtract(w, 'cable_out', 'cable_mid', 'Hollow coax1 using intermediate cutter');
subtract(w, 'cable_out_1', 'cable_mid_1', 'Hollow coax2 using intermediate cutter');
w.require('BuilderFaceCount("cable_out") = 4 And BuilderFaceCount("cable_out_1") = 4', ...
    'Both outer copper conductors must be hollow cylinders with four faces');
w.call('Note "Cutter policy: source Subtract5858 KeepOriginals=true; consume six sacrificial snapshots with false; retain all four active copper conductors."', ...
    'Record six-cutter lifetime policy');
subtract(w, 'Vivaldi_1', strjoin(cutters, ','), ...
    'Final metal Subtract5858 equivalent: six full-cylinder snapshots');
w.require(['BuilderHasExactlyNames(Array("Vivaldi_1", "cable_in", "cable_out", ' ...
    '"cable_in_1", "cable_out_1", "port1", "port2"))'], ...
    'Final six-tool subtraction failed, removed active feeds, or left model cutters');
w.require('BuilderGroupCount("Solids") = 5 And BuilderGroupCount("Sheets") = 2 And BuilderGroupCount("Unclassified") = 0', ...
    'Expected one metal body, four copper solids, two port sheets, and no unclassified geometry');

w.stage('Assign Materials');
w.call(['oEditor.AssignMaterial Array("NAME:Selections", ' ...
    '"Selections:=", "cable_in,cable_in_1,cable_out,cable_out_1"), ' ...
    'Array("NAME:Attributes", "MaterialValue:=", ' w.q('"copper"') ...
    ', "SolveInside:=", False)'], 'Assign copper and SolveInside=false to all active coax conductors');
setWCS(w, 'Global');
% Read actual CAD surfaces, rather than treating emitted coordinates as proof
% that the coax/ports exist at the required positions. GetFaceCenter is used
% only for planar disk/annulus faces selected by their analytic face areas.
g = vivaldiBuilderGeometry(p);
innerNames = {'cable_in','cable_in_1'};
outerNames = {'cable_out','cable_out_1'};
for k = 1:2
    c = g.cables(k);
    w.require(sprintf('BuilderVerifyCylinder("%s", %.17g, %.17g, %.17g, %.17g, 0, %.17g)', ...
        innerNames{k}, c.centerXY(1), c.centerXY(2), c.innerEnd(3), c.innerStart(3), p.r_cabin), ...
        ['Measured inner conductor radii, height, or position differ: ' innerNames{k}]);
    w.require(sprintf('BuilderVerifyCylinder("%s", %.17g, %.17g, %.17g, %.17g, %.17g, %.17g)', ...
        outerNames{k}, c.centerXY(1), c.centerXY(2), c.outerEnd(3), c.outerStart(3), p.r_cabmid, p.r_cabout), ...
        ['Measured hollow outer conductor radii, height, or position differ: ' outerNames{k}]);
    w.require(sprintf('BuilderVerifyCircularSheet("%s", %.17g, %.17g, %.17g, %.17g)', ...
        g.ports(k).name, g.ports(k).center(1), g.ports(k).center(2), g.ports(k).center(3), p.r_cabmid), ...
        ['Measured circular port radius, plane, or center differ: ' g.ports(k).name]);
end
end

function cylinder(w, name, x, z, radius, height, material, solveInside)
w.call(['oEditor.CreateCylinder Array("NAME:CylinderParameters", "XCenter:=", ' ...
    w.q(x) ', "YCenter:=", "0mm", "ZCenter:=", ' w.q(z) ...
    ', "Radius:=", ' w.q(radius) ', "Height:=", ' w.q(height) ...
    ', "WhichAxis:=", "Z", "NumSides:=", "0"), ' ...
    attributes(w, name, 'slot_feed_td', material, solveInside)], ['Create cylinder ' name]);
end

function text = attributes(w, name, cs, material, solveInside) %#ok<INUSD>
% Source part/material orientation is Global; primitive-reference CS is WCS.
if solveInside, inside = 'True'; else, inside = 'False'; end
text = ['Array("NAME:Attributes", "Name:=", ' w.q(name) ...
    ', "Flags:=", "", "Color:=", "(255 128 64)", "Transparency:=", 0, ' ...
    '"PartCoordinateSystem:=", "Global", "MaterialValue:=", ' ...
    w.q(['"' material '"']) ', "SurfaceMaterialValue:=", ' w.q('""') ...
    ', "SolveInside:=", ' inside ')'];
end

function text = selections(names)
text = ['Array("NAME:Selections", "Selections:=", "' names '", "NewPartsModelFlag:=", "Model")'];
end

function setWCS(w, cs)
w.call(['oEditor.SetWCS Array("NAME:SetWCS Parameter", "Working Coordinate System:=", ' ...
    w.q(cs) ', "RegionDepCSOk:=", False)'], ['Set WCS ' cs]);
end

function subtract(w, blank, tools, label)
w.call(['oEditor.Subtract Array("NAME:Selections", "Blank Parts:=", ' w.q(blank) ...
    ', "Tool Parts:=", ' w.q(tools) '), Array("NAME:SubtractParameters", "KeepOriginals:=", False)'], label);
end

function out=loadcsv(path,xColumn,yColumns)
assert(isfile(path),'VivaldiBuilder:CSVFile','CSV file does not exist.');
T=readtable(path,'VariableNamingRule','preserve');
assert(height(T)>0,'VivaldiBuilder:EmptyCSV','CSV contains no rows.');
names=T.Properties.VariableNames;
numeric=false(size(names));
for k=1:numel(names), v=T.(names{k}); numeric(k)=isnumeric(v)&&isreal(v)&&isvector(v); end
out=struct('path',char(path),'table',T,'columns',{names},'x',[],'y',[], ...
    'labels',{{}},'xLabel','','status','Imported CSV; solution provenance requires matching export metadata', ...
    'quantity',{{}},'units',{{}},'metadata',struct('source','Imported file','simulationVerified',false));
assert(any(numeric),'VivaldiBuilder:CSVNumeric','CSV has no numeric result columns.');
coord=~cellfun(@isempty,regexpi(names,'^(Freq|Frequency|Theta|Phi|Angle)(\s|\[|$)'));
varying=false(size(names));
for k=find(numeric), varying(k)=numel(unique(T.(names{k})))>1; end
if nargin<2||isempty(xColumn)
    choices=find(numeric&coord&varying);
    if numel(choices)>1
        out.status='Imported CSV has multiple varying coordinates; choose one sweep/frequency/cut before plotting.';
        return;
    end
    if isempty(choices), choices=find(numeric&coord,1); end
    if isempty(choices), choices=find(numeric,1); end
    xColumn=names{choices(1)};
end
if nargin<3||isempty(yColumns), yColumns=names(numeric&~coord&~strcmp(names,xColumn)); end
if ischar(yColumns)||isstring(yColumns), yColumns=cellstr(yColumns); end
assert(ismember(xColumn,names)&&~isempty(yColumns)&&all(ismember(yColumns,names)), ...
    'VivaldiBuilder:CSVColumns','Choose a valid X column and at least one result column.');
x=T.(xColumn); y=T{:,yColumns};
assert(isnumeric(x)&&isvector(x)&&isreal(x)&&isnumeric(y)&&isreal(y)&& ...
    all(isfinite(x(:)))&&all(isfinite(y(:))), ...
    'VivaldiBuilder:CSVValues','Selected columns must contain finite real numbers; select one valid sweep/cut first.');
out.x=x(:); out.y=y; out.labels=yColumns; out.xLabel=char(xColumn);
out.units=cell(size(yColumns)); out.quantity=cell(size(yColumns));
for k=1:numel(yColumns)
    token=regexp(yColumns{k},'\[([^\]]+)\]','tokens','once');
    if ~isempty(token), out.units{k}=token{1}; else, out.units{k}='unspecified'; end
    out.quantity{k}=strtrim(regexprep(yColumns{k},'\s*\[[^\]]+\]',''));
end
out.status='Imported actual CSV; units retained from headers. Imported files do not prove the current project was simulated.';
end

function out=measurehpbw(angles,gain)
out=struct('widthDeg',NaN,'peakAngleDeg',NaN,'peakGainDB',NaN, ...
    'leftCrossingDeg',NaN,'rightCrossingDeg',NaN,'status','Insufficient data','reason','', ...
    'thresholdDB',NaN,'periodic',false);
if ~(isnumeric(angles)&&isnumeric(gain)&&isvector(angles)&&isvector(gain)&& ...
        isreal(angles)&&isreal(gain)&&numel(angles)==numel(gain)&&numel(angles)>=3&& ...
        all(isfinite(angles(:)))&&all(isfinite(gain(:))))
    out.reason='Provide at least three finite samples of one angular cut in degrees and gain in dB.'; return;
end
[x,order]=sort(angles(:)); y=gain(order); y=y(:);
if any(diff(x)<=0), out.reason='Angles must be unique; isolate a single frequency and cut.'; return; end
if x(end)-x(1)>360+1e-8, out.reason='An angular cut cannot span more than 360 degrees.'; return; end
step=median(diff(x));
if max(diff(x))>5*step || max(diff(x))>=90
    out.reason='Angular sampling has a large gap; export a sufficiently sampled cut.'; return;
end
out.periodic=(x(end)-x(1)>=360-1.1*step);
% A duplicated physical endpoint at -180/+180 is allowed only if consistent.
if abs(x(end)-x(1)-360)<1e-8
    if abs(y(end)-y(1))>1e-5
        out.reason='The two periodic endpoints disagree; isolate one cut.'; return;
    end
    x(end)=[]; y(end)=[];
end
[peak,k]=max(y); out.peakAngleDeg=x(k); out.peakGainDB=peak; out.thresholdDB=peak-3;
if out.periodic
    n=numel(x); x=[x-360;x;x+360]; y=[y;y;y]; k=k+n;
end
left=NaN; right=NaN;
for j=k-1:-1:1
    if y(j)<=out.thresholdDB
        left=crossing(x(j),y(j),x(j+1),y(j+1),out.thresholdDB); break;
    end
end
for j=k+1:numel(x)
    if y(j)<=out.thresholdDB
        right=crossing(x(j-1),y(j-1),x(j),y(j),out.thresholdDB); break;
    end
end
out.leftCrossingDeg=left; out.rightCrossingDeg=right;
if ~isfinite(left)||~isfinite(right)
    out.reason='The cut does not contain both -3dB crossings around its strongest lobe.'; return;
end
if right-left<=0 || right-left>=360
    out.reason='A bounded main lobe could not be isolated.'; return;
end
out.widthDeg=right-left; out.status='Measured from imported pattern';
out.reason='Linear interpolation between measured samples at peak minus 3dB; convergence and sampling uncertainty remain separate.';
end

function x=crossing(x1,y1,x2,y2,target)
if y1==target, x=x1; elseif y2==target, x=x2;
elseif y2==y1, x=NaN; else, x=x1+(target-y1)*(x2-x1)/(y2-y1); end
end

function value=fielddefault(s,name,fallback)
if isfield(s,name)&&~isempty(s.(name)), value=s.(name); else, value=fallback; end
end

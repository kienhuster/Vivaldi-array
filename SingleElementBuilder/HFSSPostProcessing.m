function out = HFSSPostProcessing(action,varargin)
%HFSSPOSTPROCESSING Actual-solution reports, CSV import, and measured HPBW.
% emit(w,cfg): append guarded HFSS reports; generation is not simulation.
% load(csvPath[,xColumn,yColumns]): import an actual CSV, retaining its units.
% hpbw(anglesDeg,gainDB): -3dB crossings around the strongest sampled lobe.
switch lower(char(action))
    case 'emit', out=emitreports(varargin{:});
    case 'load', out=loadcsv(varargin{:});
    case 'hpbw', out=measurehpbw(varargin{:});
    otherwise, error('VivaldiBuilder:PostAction','Unknown postprocessing action.');
end
end

function out=emitreports(w,cfg)
solution=fielddefault(cfg,'solution',[fielddefault(cfg,'runSetup','Setup1') ' : Sweep']);
folder=fielddefault(cfg,'resultsDir',fielddefault(cfg,'outputDir',''));
assert(~isempty(folder),'VivaldiBuilder:ResultsDirectory','Select a results directory.');
frequency=fielddefault(cfg,'resultFrequencyGHz',5);
assert(isnumeric(frequency)&&isscalar(frequency)&&isfinite(frequency)&&frequency>0, ...
    'VivaldiBuilder:ReportFrequency','Report frequency must be a positive GHz value.');
excited=fielddefault(cfg,'excitedPort',1);
assert(isnumeric(excited)&&isscalar(excited)&&any(excited==[1 2]), ...
    'VivaldiBuilder:Excitation','Choose one excited port, 1 or 2.');
[~,token]=fileparts(tempname);
prefix=fielddefault(cfg,'reportPrefix',['VDB_' token]);
assert(~isempty(regexp(prefix,'^[A-Za-z][A-Za-z0-9_]*$','once')), ...
    'VivaldiBuilder:ReportName','Report prefix must contain letters, digits and underscores.');
q=@(v) w.q(v);
freq=sprintf('%.15gGHz',frequency);
modalContext='Array()';
modalFamilies='Array("Freq:=", Array("All"))';
farFamilies=['Array("Freq:=", Array(' q(freq) '), "Theta:=", Array("All"), "Phi:=", Array("All"))'];
w.declare('Dim sbrHasData, sbrVswrValid, sbrEfficiencyAvailable, sbrRequestedFieldGHz');
w.helper(reporthelpers());
w.stage('Export Actual Results');
w.require(['fs.FolderExists(' q(folder) ')'],'Results directory does not exist on the HFSS machine');
w.call(sprintf('sbrRequestedFieldGHz = %.15g',frequency),'Set requested field-data frequency in GHz');
power={'0W','0W'}; power{excited}='1W';
w.call(['oSolutions.EditSources Array(Array("IncludePortPostProcessing:=", False, "SpecifySystemPower:=", False), ' ...
    'Array("Name:=", "1:1", "Magnitude:=", ' q(power{1}) ', "Phase:=", "0deg"), ' ...
    'Array("Name:=", "2:1", "Magnitude:=", ' q(power{2}) ', "Phase:=", "0deg"))'], ...
    'Apply selected single-port excitation before evaluating actual fields');
% Configured sweeps or prior status markers do not establish solution data.
for expr={'mag(S(1,1))','mag(S(2,2))','mag(S(2,1))','mag(S(1,2))'}
    gate(w,'Modal Solution Data',solution,modalContext,modalFamilies,expr{1});
end
out=struct('solution',solution,'frequencyGHz',frequency,'reports',{{}}, ...
    'csvPaths',{{}},'metadataPath','', ...
    'status','Export commands generated; data availability checked only when HFSS executes');
[out,~]=report(w,out,prefix,folder,'SParameters','Modal Solution Data','Rectangular Plot', ...
    solution,modalContext,modalFamilies, ...
    'Array("X Component:=", "Freq", "Y Component:=", Array("dB(S(1,1))", "dB(S(2,2))", "dB(S(2,1))", "dB(S(1,2))"))');
w.call(['sbrVswrValid = SBRPassiveReflection(' q(solution) ')'], ...
    'Check finite reflection magnitudes below one before VSWR');
w.line('If sbrVswrValid Then');
[out,~]=report(w,out,prefix,folder,'VSWR','Modal Solution Data','Rectangular Plot', ...
    solution,modalContext,modalFamilies, ...
    'Array("X Component:=", "Freq", "Y Component:=", Array("VSWR(1)", "VSWR(2)"))');
w.line('Else');
w.call('Note "VSWR skipped: reflection data are absent, nonnumeric, or |Sii| >= 1 at a sample."','Record unavailable VSWR');
w.line('End If');

% Field data are required at the requested frequency, not merely S data.
gate(w,'Far Fields',solution,'Array("Context:=", "3D")',farFamilies,'RealizedGainTotal');
e0=['Array("Freq:=", Array(' q(freq) '), "Theta:=", Array("All"), "Phi:=", Array("0deg"))'];
e90=['Array("Freq:=", Array(' q(freq) '), "Theta:=", Array("All"), "Phi:=", Array("90deg"))'];
az=['Array("Freq:=", Array(' q(freq) '), "Theta:=", Array("90deg"), "Phi:=", Array("All"))'];
gate(w,'Far Fields',solution,'Array("Context:=", "Elevation")',e0,'RealizedGainTotal');
[out,~]=report(w,out,prefix,folder,'RealizedGain','Far Fields','Rectangular Plot',solution, ...
    'Array("Context:=", "Elevation")',e0, ...
    'Array("X Component:=", "Theta", "Y Component:=", Array("dB(RealizedGainTotal)"))');
specs={ ...
    'Elevation0','Elevation',e0,'Theta'; ...
    'Elevation90','Elevation',e90,'Theta'; ...
    'Azimuth','Azimuth',az,'Phi'};
for k=1:size(specs,1)
    context=['Array("Context:=", ' q(specs{k,2}) ')'];
    gate(w,'Far Fields',solution,context,specs{k,3},'RealizedGainTotal');
    [out,~]=report(w,out,prefix,folder,specs{k,1},'Far Fields','Radiation Pattern', ...
        solution,context,specs{k,3}, ...
        ['Array("Ang Component:=", ' q(specs{k,4}) ', "Mag Component:=", Array("dB(RealizedGainTotal)"))']);
end
[out,~]=report(w,out,prefix,folder,'Pattern3D','Far Fields','3D Polar Plot',solution, ...
    'Array("Context:=", "3D")',farFamilies, ...
    'Array("Phi Component:=", "Phi", "Theta Component:=", "Theta", "Mag Component:=", Array("dB(RealizedGainTotal)"))');

effFamilies=['Array("Freq:=", Array(' q(freq) '))'];
w.call(['sbrEfficiencyAvailable = SBROptionalEfficiency(' q(solution) ', ' effFamilies ')'], ...
    'Probe actual RadiationEfficiency data, optional when solver does not provide it');
w.line('If sbrEfficiencyAvailable Then');
[out,~]=report(w,out,prefix,folder,'RadiationEfficiency','Antenna Parameters','Rectangular Plot', ...
    solution,'Array("Context:=", "3D")',effFamilies, ...
    'Array("X Component:=", "Freq", "Y Component:=", Array("RadiationEfficiency"))');
w.line('End If');
metadata=fullfile(folder,[prefix '_metadata.csv']);
out.metadataPath=metadata;
w.require(['Not fs.FileExists(' q(metadata) ')'],'Result metadata path already exists; choose a new report prefix');
w.call(['SBRWriteMetadata ' q(metadata) ', ' q(prefix) ', ' q(solution) ', ' q(freq) ', ' num2str(excited)], ...
    'Export actual project, variables, source excitation and report contexts');
w.call('Note "CSV exports contain actual HFSS data. A metadata CSV records project/design, setup, requested field frequency, excitation and current variable expressions. Convergence is a separate solver check."', ...
    'Record scope of result evidence');
end

function gate(w,category,solution,context,families,expr)
w.call(['sbrHasData = SBRHasData(' w.q(category) ', ' w.q(solution) ', ' context ', ' families ', ' w.q(expr) ')'], ...
    ['Query actual solution data: ' expr]);
w.require('sbrHasData',['No actual ' expr ' data for ' solution '; solve and save fields at the requested frequency before exporting']);
end

function [out,name]=report(w,out,prefix,folder,label,category,kind,solution,context,families,components)
name=[prefix '_' label]; path=fullfile(folder,[name '.csv']);
w.require(['Not fs.FileExists(' w.q(path) ')'],'CSV path already exists; existing results are preserved');
w.call(['oReport.CreateReport ' w.q(name) ', ' w.q(category) ', ' w.q(kind) ', ' w.q(solution) ', ' ...
    context ', SBRNominalFamilies(' families '), ' components],['Create HFSS report ' label]);
w.call(['oReport.ExportToFile ' w.q(name) ', ' w.q(path)],['Export actual report CSV ' label]);
w.call(['sbrHasData = SBRNonemptyFile(' w.q(path) ')'],['Check exported CSV ' label]);
w.require('sbrHasData',['HFSS did not export a nonempty CSV for ' label]);
out.reports{end+1}=name; out.csvPaths{end+1}=path;
end


function out = HFSSAutomationBridge(action,varargin)
%HFSSAUTOMATIONBRIDGE Generate jobs portably; execute only on Windows + AEDT.
switch lower(action)
    case 'generate', out = generate(varargin{:});
    case 'launch'
        job = varargin{1}; exe = varargin{2};
        assert(ispc && isfile(exe) && endsWith(lower(exe),'ansysedt.exe'), ...
            'VivaldiBuilder:HFSSUnavailable','Select a Windows HFSS 2021 R2 ansysedt.exe. Offline generation is available.');
        args = java.util.ArrayList(); args.add(exe); args.add('-RunScript'); args.add(job.script);
        process = java.lang.ProcessBuilder(args);
        process.redirectErrorStream(true); process.redirectOutput(java.io.File(job.console));
        job.process = process.start(); job.started = tic; out = job;
    case 'poll', out = poll(varargin{1});
    case 'detect'
        out = {};
        if ~ispc, return; end
        roots = {getenv('ProgramFiles'),getenv('ProgramFiles(x86)')};
        for k = 1:numel(roots)
            if isempty(roots{k}), continue; end
            patterns = {fullfile(roots{k},'AnsysEM','**','ansysedt.exe'), ...
                fullfile(roots{k},'ANSYS Inc','**','ansysedt.exe')};
            for j = 1:numel(patterns)
                found = dir(patterns{j});
                for n = 1:numel(found), out{end+1} = fullfile(found(n).folder,found(n).name); end %#ok<AGROW>
            end
        end
        out = unique(out,'stable');
    otherwise, error('VivaldiBuilder:Action','Unknown bridge action.');
end
end

function job = generate(mode,cfg,p)
mode = lower(char(mode));
assert(ismember(mode,{'connect','build','update','validate','save','simulate','reports'}), ...
    'VivaldiBuilder:Mode','Unknown build action.');
[ok,e,~,g] = vivaldiBuilderValidate(p);
assert(ok,'VivaldiBuilder:Parameters','%s',strjoin(e,newline));
validateConfig(cfg);
if ~isfolder(cfg.outputDir), mkdir(cfg.outputDir); end
base = tempname(cfg.outputDir); mkdir(base);
job = struct('mode',mode,'script',fullfile(base,'automation.vbs'), ...
    'status',fullfile(base,'status.log'),'console',fullfile(base,'console.log'), ...
    'output',fullfile(base,[cfg.project '.aedt']), ...
    'recovery',fullfile(base,[cfg.project '_recovery.aedt']), ...
    'validation',fullfile(base,'validation.log'),'directory',base, ...
    'process',[],'timeout',cfg.timeoutSeconds,'started',[]);
if ~ismember(mode,{'build','connect'})
    sourceParams = vivaldiBuilderReadProject(cfg.input,cfg.design);
    if ~strcmp(mode,'update')
        names = fieldnames(p);
        for k = 1:numel(names)
            assert(abs(p.(names{k})-sourceParams.(names{k})) < 1e-10, ...
                'VivaldiBuilder:StaleParameters','GUI differs from project variable %s. Update the project or load its parameters first.',names{k});
        end
    end
    assert(~isfile([cfg.input '.lock']),'VivaldiBuilder:Locked','Close the source project in HFSS first; do not remove its lock.');
end
w = HFSSScript();
w.add("' Generated by Vivaldi Dual-Pol Builder Pro. Offline generation is not a build result.");
w.add('Dim fs, oApp, oDesktop, oProject, oDesign, oEditor, oBoundary, oAnalysis, oRad, oSolutions, oReport');
w.add('Dim errorNumber, errorText, statusPath, recoveryPath, validationPath, items, bounds, version');
w.add('Dim beforeObjects, created, volumeValue, portLine, result, setups');
w.add('Set fs = CreateObject("Scripting.FileSystemObject")');
w.add(['statusPath = ' HFSSScript.quote(job.status)]);
w.add(['recoveryPath = ' HFSSScript.quote(job.recovery)]);
w.add(['validationPath = ' HFSSScript.quote(job.validation)]);
w.add(fileread(fullfile(fileparts(mfilename('fullpath')),'hfss_runtime.vbs')));
w.stage('Connect');
w.checked(['Set oApp = CreateObject(' HFSSScript.quote(['Ansoft.ElectronicsDesktop.' cfg.version]) ')']);
w.checked('Set oDesktop = oApp.GetAppDesktop()');
w.checked('version = oDesktop.GetVersion()');
w.require(['InStr(1, CStr(version), ' HFSSScript.quote(cfg.version) ', vbTextCompare) > 0'], ...
    'HFSS version mismatch. Use the selected installation / COM registration.');
w.add('Note "VERSION|" & CStr(version)');
if strcmp(mode,'connect')
    w.add('State "CONNECTED", "Automation connected; no project modified"');
    w.write(job.script); return;
end
w.stage('Create Project');
w.require(['Not fs.FileExists(' HFSSScript.quote(job.output) ')'],'Output already exists.');
if strcmp(mode,'build')
    w.checked('Set oProject = oDesktop.NewProject()');
    w.api('oProject','InsertDesign','HFSS',cfg.design,'DrivenModal','');
else
    w.require(['Not fs.FileExists(' HFSSScript.quote([cfg.input '.lock']) ')'],'Source became locked. Close it first.');
    w.checked(['Set oProject = oDesktop.OpenProject(' HFSSScript.quote(canonical(cfg.input)) ')']);
end
% SaveAs happens BEFORE changing variables, ports, sources or simulation data.
w.api('oProject','SaveAs',job.output,false);
w.checked(['Set oDesign = oProject.SetActiveDesign(' HFSSScript.quote(cfg.design) ')']);
w.checked('Set oEditor = oDesign.SetActiveEditor("3D Modeler")');
modules = {'oBoundary','BoundarySetup';'oAnalysis','AnalysisSetup';'oRad','RadField'; ...
    'oSolutions','Solutions';'oReport','ReportSetup'};
for k = 1:size(modules,1)
    w.checked(['Set ' modules{k,1} ' = oDesign.GetModule(' HFSSScript.quote(modules{k,2}) ')']);
end
if strcmp(mode,'build')
    w.api('oEditor','SetModelUnits',{'NAME:Units Parameter','Units:=','mm','Rescale:=',false});
    w.api('oDesign','SetDesignSettings',{'NAME:Design Settings Data'}, ...
        {'NAME:Model Validation Settings','EntityCheckLevel:=','Strict', ...
        'IgnoreUnclassifiedObjects:=',false,'SkipIntersectionChecks:=',false});
end
if ismember(mode,{'build','update'})
    w.stage('Create Variables');
    variables = vivaldiBuilderVariables(p);
    [~,meta] = vivaldiBuilderDefaultParams();
    if strcmp(mode,'update'), variables = variables(1:numel(meta),:); end
    for k = 1:size(variables,1)
        kind = 'NAME:NewProps';
        if strcmp(mode,'update'), kind = 'NAME:ChangedProps'; end
        prop = {['NAME:' variables{k,1}],'Value:=',variables{k,2}};
        if strcmp(mode,'build'), prop = [prop(1) {'PropType:=','VariableProp','UserDef:=',true} prop(2:end)]; end
        w.api('oDesign','ChangeProperty',{'NAME:AllTabs',{'NAME:LocalVariableTab', ...
            {'NAME:PropServers','LocalVariables'},{kind,prop}}});
    end
    if strcmp(mode,'build')
        w.api('oDesign','ChangeProperty',{'NAME:AllTabs',{'NAME:LocalVariableTab', ...
            {'NAME:PropServers','LocalVariables'},{'NAME:NewProps', ...
            {'NAME:alpha','PropType:=','PostProcessingVariableProp','UserDef:=',true,'Value:=','0deg'}}}});
        HFSSGeometryBuilder.build(w,g);
        w.stage('Save Recovery'); w.api('oProject','Save');
        HFSSCoaxBuilder.build(w,g);
        HFSSCoaxBuilder.ports(w,p,g,false);
        HFSSSetupBuilder.build(w,cfg);
    else
        % Re-evaluating volume forces HFSS to regenerate the edited history.
        w.checked('volumeValue = oEditor.GetObjectVolume("Vivaldi_1")');
        w.require('CDbl(volumeValue) > 0','Rebuilt antenna has no volume.');
        HFSSGeometryBuilder.connectivity(w);
        HFSSCoaxBuilder.ports(w,p,g,true);
    end
end
w.stage('Validate');
w.checked('Inventory');
w.checked('ValidateModel');
if strcmp(mode,'simulate')
    w.stage('Run Analysis');
    HFSSSetupBuilder.sources(w,cfg.port);
    w.checked('setups = oAnalysis.GetSetups()');
    if strcmp(cfg.profile,'QuickTest')
        w.add('If InStr(1, "|" & Join(setups, "|") & "|", "|QuickTest|", vbBinaryCompare) = 0 Then');
        HFSSSetupBuilder.solution(w,'QuickTest',true,cfg);
        w.add('Else');
        HFSSSetupBuilder.sweep(w,'QuickTest',true,cfg,true);
        w.add('End If');
        w.checked('setups = oAnalysis.GetSetups()');
    end
    w.require(['InStr(1, "|" & Join(setups, "|") & "|", ' ...
        HFSSScript.quote(['|' cfg.profile '|']) ', vbBinaryCompare) > 0'],'Selected solver profile does not exist in this project.');
    w.api('oDesign','Analyze',cfg.profile);
    points = 61; if strcmp(cfg.profile,'QuickTest'), points = round((cfg.fStop-cfg.fStart)/cfg.fStep)+1; end
    w.checked(['RequireSolution ' HFSSScript.quote([cfg.profile ' : Sweep']) ', ' num2str(points)]);
    HFSSPostProcessing.reports(w,cfg,job);
elseif strcmp(mode,'reports')
    w.checked(['RequireSolution ' HFSSScript.quote([cfg.profile ' : Sweep']) ', 1']);
    HFSSPostProcessing.reports(w,cfg,job);
end
w.stage('Save'); w.api('oProject','Save');
w.require(['fs.FileExists(' HFSSScript.quote(job.output) ')'],'Saved project file is missing.');
% Close only the job's own copy, allowing subsequent Validate/Run jobs to
% open it safely. Failed jobs remain open for CAD inspection and recovery.
w.checked('created = oProject.GetName()');
w.api('oDesktop','CloseProject',HFSSScript.raw('created'));
state = 'VALIDATED';
if strcmp(mode,'build'), state = 'BUILT';
elseif strcmp(mode,'update'), state = 'UPDATED';
elseif strcmp(mode,'simulate'), state = 'SIMULATED';
elseif strcmp(mode,'reports'), state = 'EXPORTED';
elseif strcmp(mode,'save'), state = 'SAVED'; end
w.add(['State ' HFSSScript.quote(state) ', ' HFSSScript.quote(job.output)]);
w.write(job.script);
save(fullfile(base,'job.mat'),'cfg','p','job');
end

function validateConfig(cfg)
for key = {'project','design'}
    value = cfg.(key{1});
    assert(ischar(value) && ~isempty(regexp(value,'^[A-Za-z][A-Za-z0-9_]*$','once')), ...
        'VivaldiBuilder:Name','Project and design names must be simple identifiers.');
end
assert(strcmp(cfg.version,'2021.2'),'VivaldiBuilder:Version','This builder targets HFSS 2021 R2 (2021.2).');
assert(ismember(cfg.profile,{'Setup1','QuickTest'}) && ismember(cfg.port,[1 2]), ...
    'VivaldiBuilder:Profile','Unknown solver profile or excitation port.');
validateattributes(cfg.timeoutSeconds,{'numeric'},{'real','finite','scalar','positive'});
validateattributes(cfg.reportFrequency,{'numeric'},{'real','finite','scalar','positive'});
for key = {'fStart','fStop','fStep'}
    validateattributes(cfg.(key{1}),{'numeric'},{'real','finite','scalar','positive'});
end
assert(cfg.fStop >= cfg.fStart && (cfg.fStop-cfg.fStart)/cfg.fStep <= 10000, ...
    'VivaldiBuilder:Sweep','Invalid or excessive QuickTest sweep.');
assert(~isempty(cfg.outputDir),'VivaldiBuilder:Output','Output directory is required.');
end

function state = poll(job)
state = struct('state','LAUNCHED','log','','terminal',false,'alive',true,'timedOut',false);
if isfile(job.status)
    state.log = HFSSScript.read(job.status);
    tokens = regexp(state.log,'(?m)^STATE\|([A-Z_]+)\|','tokens');
    if ~isempty(tokens), state.state = tokens{end}{1}; end
end
state.terminal = ismember(state.state,{'FAILED','CONNECTED','BUILT','UPDATED','VALIDATED','SAVED','SIMULATED','EXPORTED'});
if isfield(job,'process') && ~isempty(job.process)
    state.alive = job.process.isAlive();
    % AEDT can dispatch the script to an existing Desktop and then terminate
    % its launcher. Only the script's terminal record proves the job outcome.
    if ~state.terminal && ~state.alive
        state.state = 'WAITING_FOR_SCRIPT';
        state.log = [state.log newline 'Launcher exited; awaiting the HFSS script result.'];
    end
    if ~state.terminal && toc(job.started) > job.timeout
        state.state = 'TIMED_OUT'; state.terminal = true; state.timedOut = true;
        state.log = [state.log newline 'Timeout: HFSS may still be executing. Inspect it before another job. No success assumed; process was not killed.'];
    end
end
end

function file = canonical(file)
[ok,attributes] = fileattrib(file);
assert(logical(ok),'VivaldiBuilder:Input','Cannot resolve input file.');
file = attributes.Name;
end

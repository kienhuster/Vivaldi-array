function HFSSGeometryBuilder(w, p) %#ok<INUSD>
%HFSSGEOMETRYBUILDER Rebuild source flare, cavity, and dual-pol metal via API.
% Requires the design expressions to have been created by the bridge. All
% geometry remains parameterized in HFSS; p supplies their independent values.
% Source: 17_10_2026_vivaldi.aedt, dual_pol_vivaldi_patch_Wflare_20.
w.helper(HFSSCADHelpers());
w.call('oEditor.SetModelUnits Array("NAME:Units Parameter", "Units:=", "mm", "Rescale:=", False)', ...
    'Set source model units to mm before creating geometry');
w.stage('Create Coordinate Systems');
createCS(w, 'slot_t_td', 'Global', ...
    {'(slot_feed_w/2)*exp(slot_t_L*r_flare)', '0mm', 'slot_t_L'});
createCS(w, 'slot_feed_td', 'Global', {'-x_feed', '0mm', 'z_feed'});
createCS(w, 'patch_td', 'Global', {'aperture_w/2', '0mm', 'L_flare'});
createCS(w, 'RelativeCS1', 'patch_td', {'0mm', '-thickness/2', '0mm'});

w.stage('Build Flare');
setWCS(w, 'Global');
equationSurface(w, 'EquationSurface1', 'L_flare');
equationSurface(w, 'EquationSurface2', 'slot_t_L');
w.call('BuilderCloneNamed "EquationSurface2", "EquationSurface2_1", "copy"', ...
    'Copy unrotated short flare before transition rotation');
w.call('Note "Cutter policy: source Subtract5914 KeepOriginals=true; consume sacrificial EquationSurface2_1 with false; preserve EquationSurface2."', ...
    'Record short-flare cutter lifetime policy');
subtract(w, 'EquationSurface1', 'EquationSurface2_1', ...
    'Remove unrotated short flare from long flare');
w.require('BuilderContainsName(BuilderObjectNames(), "EquationSurface2")', ...
    'Original short flare was lost before rotation');
setWCS(w, 'slot_t_td');
w.call(['oEditor.Rotate ' selections('EquationSurface2') ...
    ', Array("NAME:RotateParameters", "RotateAxis:=", "Y", "RotateAngle:=", "deg_slot_t")'], ...
    'Rotate short transition around slot_t_td Y axis');

w.stage('Build Cavity');
setWCS(w, 'slot_feed_td');
rectangle(w, 'Rectangle1', 'slot_feed_td', '0mm', '0mm', ...
    '-h3_slot_feed', 'slot_feed_w', 'vacuum');
rectangle(w, 'Rectangle2', 'slot_feed_td', '0mm', '-h3_slot_feed', ...
    '-slot_feed_w', 'slot_feed_w+h2+cavity_w', 'vacuum');
rectangle(w, 'Rectangle3', 'slot_feed_td', 'slot_feed_w+h2', ...
    '-(h3_slot_feed+slot_feed_w)', 'cavity_L', 'cavity_w', 'vacuum');
unite(w, 'EquationSurface1,EquationSurface2,Rectangle1,Rectangle2,Rectangle3', ...
    'Unite complete flare, angled transition, slot, and cavity cutter');
w.require('BuilderHasExactlyNames(Array("EquationSurface1"))', ...
    'Composite cavity failed or left unexpected cutter geometry');

w.stage('Build Metal Sheets');
setWCS(w, 'patch_td');
rectangle(w, 'Vivaldi_1', 'patch_td', '0mm', '0mm', ...
    '-L_patch', '-aperture_w', 'aluminum');
subtract(w, 'Vivaldi_1', 'EquationSurface1', 'Cut complete cavity from metal sheet');
w.call(['oEditor.ThickenSheet ' selections('Vivaldi_1') ...
    ', Array("NAME:SheetThickenParameters", "Thickness:=", "thickness", "BothSides:=", True)'], ...
    'ThickenSheet symmetric total thickness (source BothSides=true)');
w.require('BuilderGroupCount("Solids") = 1 And BuilderGroupCount("Sheets") = 0', ...
    'ThickenSheet did not produce exactly one metal solid');

w.stage('Create Dual-Pol');
setWCS(w, 'RelativeCS1');
w.call('BuilderCloneNamed "Vivaldi_1", "Vivaldi_2", "rotate"', ...
    'DuplicateAroundAxis metal -90deg at RelativeCS1');
moveSecond(w, 'Vivaldi_2');
w.call(['oEditor.CreateBox Array("NAME:BoxParameters", "XPosition:=", "0mm", ' ...
    '"YPosition:=", "0mm", "ZPosition:=", "0mm", "XSize:=", "thickness", ' ...
    '"YSize:=", "thickness", "ZSize:=", "-L_patch"), ' ...
    attributes(w, 'Box1', 'RelativeCS1', 'aluminum', false)], ...
    'Create connector Box1 in RelativeCS1');
setWCS(w, 'Global');
w.call(['oEditor.CreateBox Array("NAME:BoxParameters", ' ...
    '"XPosition:=", "(de_L+thickness)/2", "YPosition:=", "-(de_W-aperture_w)/2", ' ...
    '"ZPosition:=", "z_feed-h3_slot_feed-slot_feed_w", "XSize:=", "-de_L", ' ...
    '"YSize:=", "de_W", "ZSize:=", "-h_de"), ' ...
    attributes(w, 'De', 'Global', 'aluminum', false)], ...
    'Create parameterized aluminum base');
unite(w, 'Vivaldi_1,Vivaldi_2,Box1,De', ...
    'Unite orthogonal plates, connector, and base');
w.require('BuilderHasExactlyNames(Array("Vivaldi_1")) And BuilderGroupCount("Solids") = 1', ...
    'Dual-pol metal Unite failed or left extra objects; inspect contact geometry');
w.stage('Assign Materials');
w.call(['oEditor.AssignMaterial Array("NAME:Selections", "Selections:=", "Vivaldi_1"), ' ...
    'Array("NAME:Attributes", "MaterialValue:=", ' w.q('"aluminum"') ...
    ', "SolveInside:=", False)'], 'Assign aluminum and SolveInside=false to metal body');
end

function createCS(w, name, parent, origin)
% Set both the parent and the local origin explicitly: changing Reference CS
% alone can preserve the old Global location in some Modeler workflows.
setWCS(w, parent);
w.call(['oEditor.CreateRelativeCS Array("NAME:RelativeCSParameters", ' ...
    '"Mode:=", "Axis/Position", "OriginX:=", ' w.q(origin{1}) ...
    ', "OriginY:=", ' w.q(origin{2}) ', "OriginZ:=", ' w.q(origin{3}) ...
    ', "XAxisXvec:=", "1mm", "XAxisYvec:=", "0mm", "XAxisZvec:=", "0mm", ' ...
    '"YAxisXvec:=", "0mm", "YAxisYvec:=", "1mm", "YAxisZvec:=", "0mm"), ' ...
    'Array("NAME:Attributes", "Name:=", ' w.q(name) ')'], ['Create CS ' name]);
w.call(['oEditor.ChangeProperty Array("NAME:AllTabs", Array("NAME:Geometry3DCSTab", ' ...
    'Array("NAME:PropServers", ' w.q(name) '), Array("NAME:ChangedProps", ' ...
    'Array("NAME:Reference CS", "Value:=", ' w.q(parent) '))))'], ['Set parent of ' name]);
w.call(['oEditor.ChangeProperty Array("NAME:AllTabs", Array("NAME:Geometry3DCSTab", ' ...
    'Array("NAME:PropServers", ' w.q(name) '), Array("NAME:ChangedProps", ' ...
    'Array("NAME:Origin", "X:=", ' w.q(origin{1}) ', "Y:=", ' w.q(origin{2}) ...
    ', "Z:=", ' w.q(origin{3}) '))))'], ['Set symbolic local origin of ' name]);
end

function equationSurface(w, name, uEnd)
w.call(['oEditor.CreateEquationSurface Array("NAME:EquationBasedSurfaceParameters", ' ...
    '"XuvFunction:=", "_v*((slot_feed_w/2)*exp((_u)*r_flare))", ' ...
    '"YuvFunction:=", "0", "ZuvFunction:=", "_u", "uStart:=", "0", ' ...
    '"uEnd:=", ' w.q(uEnd) ', "vStart:=", "-1", "vEnd:=", "1", "Version:=", 1), ' ...
    attributes(w, name, 'Global', 'vacuum', true)], ['Create equation surface ' name]);
end

function rectangle(w, name, cs, x, z, width, height, material)
% Normal Y: HFSS Width is along Z; Height is along X, as source vertices show.
w.call(['oEditor.CreateRectangle Array("NAME:RectangleParameters", "IsCovered:=", False, ' ...
    '"XStart:=", ' w.q(x) ', "YStart:=", "0mm", "ZStart:=", ' w.q(z) ...
    ', "Width:=", ' w.q(width) ', "Height:=", ' w.q(height) ...
    ', "WhichAxis:=", "Y"), ' attributes(w, name, cs, material, strcmp(material, 'vacuum'))], ...
    ['Create rectangle wire ' name]);
w.call(['oEditor.CoverLines ' selections(name)], ['CoverLines ' name]);
end

function text = attributes(w, name, cs, material, solveInside) %#ok<INUSD>
% WCS controls primitive-reference geometry. PartCoordinateSystem controls
% material orientation and is Global on EVERY top-level source object.
if solveInside, inside = 'True'; else, inside = 'False'; end
text = ['Array("NAME:Attributes", "Name:=", ' w.q(name) ...
    ', "Flags:=", "", "Color:=", "(143 175 143)", "Transparency:=", 0, ' ...
    '"PartCoordinateSystem:=", "Global", "MaterialValue:=", ' ...
    w.q(['"' material '"']) ', "SurfaceMaterialValue:=", ' w.q('""') ...
    ', "SolveInside:=", ' inside ')'];
end

function setWCS(w, cs)
w.call(['oEditor.SetWCS Array("NAME:SetWCS Parameter", "Working Coordinate System:=", ' ...
    w.q(cs) ', "RegionDepCSOk:=", False)'], ['Set WCS ' cs]);
end

function text = selections(names)
text = ['Array("NAME:Selections", "Selections:=", "' names '", "NewPartsModelFlag:=", "Model")'];
end

function subtract(w, blank, tools, label)
w.call(['oEditor.Subtract Array("NAME:Selections", "Blank Parts:=", ' w.q(blank) ...
    ', "Tool Parts:=", ' w.q(tools) '), Array("NAME:SubtractParameters", "KeepOriginals:=", False)'], label);
end

function unite(w, names, label)
w.call(['oEditor.Unite ' selections(names) ...
    ', Array("NAME:UniteParameters", "KeepOriginals:=", False)'], label);
end

function moveSecond(w, name)
w.call(['oEditor.Move ' selections(name) ...
    ', Array("NAME:TranslateParameters", "TranslateVectorX:=", "0mm", ' ...
    '"TranslateVectorY:=", "thickness", "TranslateVectorZ:=", "0mm")'], ...
    ['Move ' name ' by thickness along RelativeCS1 Y']);
end
